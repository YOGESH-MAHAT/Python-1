#Arthimetic operators
print(5+3) #8
print(5-3) #2
print(5*3) #15
print(5/3) #1.6666666666666667
print(5//3) #1
print(5%3) #2
print(5**3) #125
# relational operators
print(5>3) #true
print(5<3) #false
print(5>=3) #true
print(5<=3) #false
print(5==3) #false
print(5!=3) #true
# logical operators
print(5>3 and 5<3) #false
print(5>3 or 5<3) #true
print(not(5>3)) #false
#Assignment operators
x = 5
print(x) #5
x += 3
print(x) #8
x -= 3
print(x) #5
x *= 3
print(x) #15
x /= 3
print(x) #5.0
x //= 3
print(x) #1.0
x %= 3
print(x) #1.0
x **= 3
print(x) #1.0

#Bitwise operators
print(5 & 3) #1
print(5 | 3) #7
print(5 ^ 3) #6
print(~5) #-6
print(5 << 1) #10
print(5 >> 1) #2

#Membership & identity operators
print(5 in [1, 2, 3, 4, 5]) #true
print(5 not in [1, 2, 3, 4, 5]) #false
print(5 is 5) #true
print(5 is not 5) #false